// Compiles the schema.org vocabulary into a compact lookup module used by the validator.
// Usage: node scripts/build-vocab.mjs [path-to-schemaorg-current-https.jsonld]
// Without a path, downloads the latest release from schema.org.
import { readFile, writeFile } from 'node:fs/promises';

const SOURCE = 'https://schema.org/version/latest/schemaorg-current-https.jsonld';
const OUT = new URL('../src/lib/vocab-data.js', import.meta.url);

const raw = process.argv[2]
  ? await readFile(process.argv[2], 'utf8')
  : await (await fetch(SOURCE)).text();
const graph = JSON.parse(raw)['@graph'];

const strip = (id) => id.replace(/^schema:/, '');
const ids = (v) => (v == null ? [] : [].concat(v).map((x) => strip(x['@id'])).filter((x) => !x.includes(':')));

const classes = {};
const props = {};
const enumMembers = {};
const superseded = {};

for (const n of graph) {
  const kinds = [].concat(n['@type']);
  const name = strip(n['@id']);
  if (name.includes(':')) continue;
  if (n['schema:supersededBy']) superseded[name] = ids(n['schema:supersededBy'])[0];
  if (kinds.includes('rdfs:Class')) {
    classes[name] = ids(n['rdfs:subClassOf']);
  } else if (kinds.includes('rdf:Property')) {
    props[name] = [ids(n['schema:domainIncludes']), ids(n['schema:rangeIncludes'])];
  } else {
    // Enumeration members are typed with their enumeration class, e.g. schema:InStock a schema:ItemAvailability.
    const enumType = kinds.map((k) => strip(k)).find((k) => !k.includes(':'));
    if (enumType) enumMembers[name] = enumType;
  }
}

const data = { builtAt: new Date().toISOString().slice(0, 10), classes, props, enumMembers, superseded };
await writeFile(OUT, `// Generated by scripts/build-vocab.mjs from ${SOURCE}. Do not edit by hand.\nexport default ${JSON.stringify(data)};\n`);
console.log(`classes=${Object.keys(classes).length} props=${Object.keys(props).length} enumMembers=${Object.keys(enumMembers).length} superseded=${Object.keys(superseded).length}`);
